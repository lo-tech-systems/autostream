class TestSupervisorScriptImports:
    """All five supervisor scripts must load without import errors."""

    @pytest.mark.parametrize("script", [
        "autostream_admin",
        "autostream_updater",
        "autostream_dial_updater",
        "autostream_update_retry",
        "autostream_update_support.py",
    ])
    def test_script_loads_without_error(self, script):
        script_path = REPO_ROOT / "supervisor" / script
        if not script_path.exists():
            pytest.skip(f"supervisor/{script} not found")
        alias = f"_p9_{script.replace('.', '_')}"
        if script_path.suffix == ".py":
            loader = SourceFileLoader(alias, str(script_path))
            spec = importlib.util.spec_from_loader(alias, loader)
            mod = importlib.util.module_from_spec(spec)
            _inject_posix_stubs()
            try:
                loader.exec_module(mod)
            except SystemExit:
                pass   # scripts that call sys.exit() at module level
            finally:
                _remove_posix_stubs()
        else:
            try:
                mod = load_supervisor_script(script, alias)
            except SystemExit:
                pass


def _inject_posix_stubs():
    for stub in ("fcntl", "pwd", "grp"):
        if stub not in sys.modules:
            sys.modules[stub] = MagicMock()


def _remove_posix_stubs():
    for stub in ("fcntl", "pwd", "grp"):
        sys.modules.pop(stub, None)


