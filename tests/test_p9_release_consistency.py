class TestDialProtocolSchemaFields:
    """Key endpoint examples in DIAL_PROTOCOL.md contain required fields."""

    @pytest.fixture(scope="class")
    def doc_text(self):
        p = REPO_ROOT / "docs" / "dial" / "DIAL_PROTOCOL.md"
        if not p.exists():
            pytest.skip("DIAL_PROTOCOL.md not found")
        return _read(p)

    def _find_json_with_field(self, doc_text: str, field: str) -> list[dict]:
        """Return all parsed JSON blocks that contain *field* at the top level."""
        results = []
        for block in _extract_json_blocks(doc_text):
            try:
                obj = json.loads(block)
            except json.JSONDecodeError:
                continue
            if isinstance(obj, dict) and field in obj:
                results.append(obj)
        return results

    def test_audio_status_example_has_playing_field(self, doc_text):
        matches = self._find_json_with_field(doc_text, "playing")
        assert matches, (
            "DIAL_PROTOCOL.md must have a JSON example with a 'playing' field "
            "for the /api/audio/status response"
        )
        assert isinstance(matches[0]["playing"], bool), (
            "'playing' must be a boolean in the /api/audio/status example"
        )

    def test_audio_status_example_has_outputs_field(self, doc_text):
        matches = self._find_json_with_field(doc_text, "outputs")
        assert matches, (
            "DIAL_PROTOCOL.md must have a JSON example with an 'outputs' field"
        )

    def test_dial_volume_request_has_dial_id_and_delta(self, doc_text):
        matches = self._find_json_with_field(doc_text, "dial_id")
        assert matches, (
            "DIAL_PROTOCOL.md must have a JSON example with a 'dial_id' field "
            "for the /api/dial/volume request"
        )
        assert "delta" in matches[0], (
            "'delta' must appear in the same example as 'dial_id'"
        )

    def test_dial_volume_success_response_has_ok_and_volume(self, doc_text):
        matches = self._find_json_with_field(doc_text, "volume")
        assert matches, (
            "DIAL_PROTOCOL.md must have a JSON example with a 'volume' field "
            "for the /api/dial/volume success response"
        )
        assert "ok" in matches[0], (
            "'ok' must appear in the same example as 'volume'"
        )

    def test_configure_get_response_has_required_fields(self, doc_text):
        matches = self._find_json_with_field(doc_text, "step_percent")
        assert matches, (
            "DIAL_PROTOCOL.md must have a JSON example for GET /configure "
            "containing 'step_percent'"
        )
        required = {"step_percent", "pin_set", "name", "version", "auto_update"}
        missing = required - set(matches[0].keys())
        assert not missing, (
            f"GET /configure example is missing fields: {sorted(missing)}"
        )

    def test_recovery_status_response_has_required_fields(self, doc_text):
        matches = self._find_json_with_field(doc_text, "volume_confirmed")
        assert matches, (
            "DIAL_PROTOCOL.md must have a JSON example for /recovery_status "
            "containing 'volume_confirmed'"
        )
        assert "active" in matches[0], (
            "'active' must appear alongside 'volume_confirmed' in /recovery_status example"
        )

    def test_update_status_response_documents_state_field(self, doc_text):
        # The /update/status example uses pipe notation ("idle"|"running"|...)
        # which is not parseable as JSON. Check for field presence in raw text.
        assert '"state"' in doc_text, (
            "DIAL_PROTOCOL.md must document a 'state' field for /update/status"
        )
        assert '"version"' in doc_text, (
            "DIAL_PROTOCOL.md must document a 'version' field for /update/status"
        )
        # Verify the documented state values are the canonical set
        for state_val in ("idle", "running", "complete", "failed"):
            assert state_val in doc_text, (
                f"DIAL_PROTOCOL.md must document state value '{state_val}' "
                "for GET /update/status"
            )


