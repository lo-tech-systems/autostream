class TestRequirementsLock:
    """dial/requirements.lock must be present, parseable, and consistent."""

    @pytest.fixture(scope="class")
    def lock_path(self):
        p = REPO_ROOT / "dial" / "requirements.lock"
        if not p.exists():
            pytest.skip("dial/requirements.lock not found")
        return p

    @pytest.fixture(scope="class")
    def lock_text(self, lock_path):
        return _read(lock_path)

    @pytest.fixture(scope="class")
    def req_text(self):
        p = REPO_ROOT / "dial" / "requirements.txt"
        if not p.exists():
            pytest.skip("dial/requirements.txt not found")
        return _read(p)

    def test_lock_file_exists(self, lock_path):
        assert lock_path.exists(), "dial/requirements.lock must exist alongside requirements.txt"

    def test_lock_file_is_not_empty(self, lock_text):
        assert lock_text.strip(), "dial/requirements.lock must not be empty"

    def test_lock_file_contains_hash_lines(self, lock_text):
        assert "--hash=sha256:" in lock_text, (
            "dial/requirements.lock must contain --hash= lines "
            "(regenerate with pip-compile --generate-hashes)"
        )

    def test_direct_dependency_pinned_in_lock(self, lock_text, req_text):
        """Every package from requirements.txt appears pinned in requirements.lock."""
        for line in req_text.splitlines():
            line = line.strip()
            if not line or line.startswith("#"):
                continue
            pkg = re.split(r"[=<>!;#]", line)[0].strip().lower()
            assert pkg in lock_text.lower(), (
                f"Direct dependency '{pkg}' from requirements.txt "
                "not found in requirements.lock"
            )

    def test_transitive_dep_colorzero_in_lock(self, lock_text):
        """colorzero is a known transitive dep of gpiozero; it must be pinned."""
        assert "colorzero" in lock_text.lower(), (
            "colorzero (transitive dependency of gpiozero) is missing from "
            "dial/requirements.lock; regenerate with pip-compile --generate-hashes"
        )

    def test_lock_file_generated_by_pip_compile(self, lock_text):
        """Confirm the lock file was generated by pip-compile, not written by hand."""
        assert "pip-compile" in lock_text, (
            "requirements.lock header comment must reference pip-compile "
            "(regenerate: pip-compile --generate-hashes dial/requirements.txt -o dial/requirements.lock)"
        )


